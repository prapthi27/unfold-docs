import { AudienceMode, GlossaryItem } from '@/types';
import { AUDIENCE_OPTIONS } from './sample-data';

export interface ExportReportParams {
  originalText: string;
  simplifiedText: string;
  keyTakeaways?: string[];
  glossary?: GlossaryItem[];
  audienceMode: AudienceMode;
  fileName?: string | null;
}

export function generateMarkdownReport({
  originalText,
  simplifiedText,
  keyTakeaways = [],
  glossary = [],
  audienceMode,
  fileName,
}: ExportReportParams): string {
  const audience = AUDIENCE_OPTIONS.find((a) => a.id === audienceMode);
  const timestamp = new Date().toISOString().replace('T', ' ').substring(0, 19);

  let markdown = `# UnfoldDocs — Document Simplification Report\n\n`;
  markdown += `> **Generated:** ${timestamp} UTC  \n`;
  markdown += `> **Target Audience:** ${audience?.label ?? audienceMode} (${audience?.readingGrade ?? 'Custom'})  \n`;
  markdown += `> **Source Document:** ${fileName || 'Direct Text Input'}\n\n`;
  markdown += `---\n\n`;

  // Key Takeaways Section
  if (keyTakeaways.length > 0) {
    markdown += `## 1. Key Takeaways & Obligations\n\n`;
    keyTakeaways.forEach((item) => {
      markdown += `- ${item}\n`;
    });
    markdown += `\n---\n\n`;
  }

  // Simplified Text Section
  markdown += `## 2. Plain-Language Simplification\n\n`;
  markdown += `${simplifiedText || '_No simplified content generated yet._'}\n\n`;
  markdown += `---\n\n`;

  // Jargon Glossary Section
  if (glossary.length > 0) {
    markdown += `## 3. Jargon Glossary (Contextual Plain-English Definitions)\n\n`;
    markdown += `| Complex Term | Plain-English Meaning in Context |\n`;
    markdown += `| :--- | :--- |\n`;
    glossary.forEach((item) => {
      const safeTerm = item.term.replace(/\|/g, '\\|');
      const safeDef = item.definition.replace(/\|/g, '\\|');
      markdown += `| **${safeTerm}** | ${safeDef} |\n`;
    });
    markdown += `\n---\n\n`;
  }

  // Original Source Text Section
  markdown += `## 4. Original Source Document Text\n\n`;
  markdown += `\`\`\`text\n${originalText || '_No original text provided._'}\n\`\`\`\n\n`;
  markdown += `---\n\n`;
  markdown += `*Report generated by [UnfoldDocs](https://github.com/unfold-docs) — AI-Powered Document Comprehension & Fidelity Workspace.*\n`;

  return markdown;
}

export function downloadMarkdownFile(content: string, filename = 'unfolddocs-report.md'): void {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
